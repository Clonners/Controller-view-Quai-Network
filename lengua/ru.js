  const g3 = (n, f1, f2) => { const r = [], c = Math.floor(n / 100), du = n % 100, u = du < 20 ? du : du % 10; if (c) r.push(C[c]); if (du >= 20) r.push(DZ[Math.floor(du / 10)]); if (u) r.push(u === 1 ? f1 : u === 2 ? f2 : U[u]); return r; };
