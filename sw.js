/* Kataribe panel: the offline copy is retired (standard rule O25: a published page is never hidden behind a saved copy).
   This worker only deletes the old caches and unregisters itself, so browsers that installed the old one load the live page. */
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.map((k) => caches.delete(k))))
      .then(() => self.registration.unregister())
      .then(() => self.clients.matchAll({ type: 'window' }))
      .then((clients) => clients.forEach((c) => c.navigate(c.url)))
  );
});
